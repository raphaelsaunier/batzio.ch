#!/usr/bin/env node
/**
 * Bundles the engine (src/entry.ts) into bundle/batzio-local.js, the one script
 * the Apple, Android and Windows apps load for their on-device mode.
 *
 *   pnpm --filter @batzio/local build
 *   pnpm --filter @batzio/local check   # fails when the committed bundle is stale
 */
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "rolldown";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "bundle", "batzio-local.js");
const check = process.argv.includes("--check");
const outDir = check ? mkdtempSync(join(tmpdir(), "batzio-local-")) : join(root, "bundle");
const file = join(outDir, "batzio-local.js");

await build({
  input: join(root, "src/entry.ts"),
  platform: "browser",
  resolve: {
    alias: {
      "cloudflare:workers": join(root, "src/shims/workers-env.ts"),
      // Batzi (Claude) needs the network; the engine only reaches it with an API key.
      "@anthropic-ai/sdk": join(root, "src/shims/offline-sdk.ts"),
    },
  },
  transform: { target: "es2022", define: { "process.env.NODE_ENV": '"production"' } },
  logLevel: "warn",
  output: {
    file,
    format: "iife",
    minify: true,
    codeSplitting: false,
    comments: { legal: false },
    banner: "/* Batzio on-device engine. Generated by packages/local/scripts/build.mjs — do not edit. */",
  },
});

if (check) {
  const fresh = readFileSync(file, "utf8");
  rmSync(outDir, { recursive: true, force: true });
  let committed = "";
  try {
    committed = readFileSync(target, "utf8");
  } catch {}
  if (fresh !== committed) {
    console.error("packages/local/bundle/batzio-local.js is stale: run `pnpm --filter @batzio/local build`.");
    process.exit(1);
  }
  console.log("On-device engine bundle is up to date.");
} else {
  console.log(`${target} (${Math.round(readFileSync(target).length / 1024)} KB)`);
}
