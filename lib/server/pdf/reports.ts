interface Column {
  label: string;
  width: number;
  align?: "left" | "right";
}

async function start(ctx: Ctx, title: string, subtitle: string) {
  const company = await getSettings(ctx, "company");
  const w = await PdfWriter.create({ title: `${title} – ${company.name}`, author: company.name });
  const header = (writer: PdfWriter) => {
    writer.rect(0, 0, A4.width, 4, COLORS.accent);
    writer.text(company.name || ctx.tenant.name, writer.margin.left, 14 * MM, { size: 9, bold: true, color: COLORS.accent });
    writer.text(`${title} · ${subtitle}`, A4.width - writer.margin.right, 14 * MM, { size: 8, color: COLORS.muted, align: "right" });
    writer.y = 24 * MM;
  };
  header(w);
  w.text(title, w.margin.left, w.y, { size: 16, bold: true });
  w.y += 20;
  w.text(subtitle, w.margin.left, w.y, { size: 9, color: COLORS.muted });
  w.y += 22;
  w.onNewPage = header;
  return { w, company };
}

function table(w: PdfWriter, columns: Column[], rows: { cells: string[]; bold?: boolean; shade?: boolean }[]) {
  const total = columns.reduce((s, c) => s + c.width, 0);
  const scale = w.contentWidth / total;
  const xs: number[] = [];
  let x = w.margin.left;
  for (const c of columns) {
    xs.push(x);
    x += c.width * scale;
  }
  const head = () => {
    w.rect(w.margin.left - 2, w.y - 3, w.contentWidth + 4, 15, COLORS.accentLight);
    columns.forEach((c, i) =>
      w.text(c.label, c.align === "right" ? xs[i] + c.width * scale - 2 : xs[i], w.y, { size: 7.5, bold: true, color: COLORS.accent, align: c.align === "right" ? "right" : "left" }),
    );
    w.y += 17;
  };
  head();
  for (const row of rows) {
    if (w.remaining() < 14) {
      w.addPage();
      head();
    }
    if (row.shade) w.rect(w.margin.left - 2, w.y - 3, w.contentWidth + 4, 14, COLORS.accentLight);
    row.cells.forEach((cell, i) => {
      const c = columns[i];
      const width = c.width * scale - 4;
      let text = cell ?? "";
      while (text.length > 1 && w.font.widthOfTextAtSize(text, 8.5) > width) text = text.slice(0, -2) + "…";
      w.text(text, c.align === "right" ? xs[i] + c.width * scale - 2 : xs[i], w.y, { size: 8.5, bold: row.bold, align: c.align === "right" ? "right" : "left" });
    });
    w.y += 13;
  }
}

export async function renderReportPdf(ctx: Ctx, report: Report): Promise<Uint8Array> {
  const subtitle = report.period.from ? `${formatDate(report.period.from)} – ${formatDate(report.period.to)}` : `As of ${formatDate(report.period.to)}`;
  const { w } = await start(ctx, report.title, subtitle);
  const rows: { cells: string[]; bold?: boolean; shade?: boolean }[] = [];
  for (const s of report.sections) {
    rows.push({ cells: ["", s.title, ""], bold: true, shade: true });
    for (const l of s.lines) {
      rows.push({ cells: [l.number ?? "", `${"   ".repeat(l.level)}${l.label}`, formatAmount(l.amount)], bold: l.kind !== "account" });
    }
  }
  if (report.result) rows.push({ cells: ["", report.result.label, formatAmount(report.result.amount)], bold: true, shade: true });
  table(w, [{ label: "Account", width: 14 }, { label: "Description", width: 70 }, { label: "CHF", width: 22, align: "right" }], rows);
  w.finalizeFooters(`Generated by Batzio on ${formatDate(new Date().toISOString().slice(0, 10))}`);
  return w.save();
}

export async function renderTrialBalancePdf(ctx: Ctx, tb: Awaited<ReturnType<typeof trialBalance>>): Promise<Uint8Array> {
  const { w } = await start(ctx, "Trial balance", `${formatDate(tb.period.from)} – ${formatDate(tb.period.to)}`);
  table(
    w,
    [
      { label: "Account", width: 10 },
      { label: "Name", width: 40 },
      { label: "Opening", width: 16, align: "right" },
      { label: "Debit", width: 16, align: "right" },
      { label: "Credit", width: 16, align: "right" },
      { label: "Balance", width: 16, align: "right" },
    ],
    [
      ...tb.rows.map((r) => ({ cells: [r.number, r.name, formatAmount(r.opening), formatAmount(r.debit), formatAmount(r.credit), formatAmount(r.balance)] })),
      { cells: ["", "Total", "", formatAmount(tb.totals.debit), formatAmount(tb.totals.credit), ""], bold: true, shade: true },
    ],
  );
  w.finalizeFooters("Generated by Batzio");
  return w.save();
}

export async function renderLedgerPdf(ctx: Ctx, l: Awaited<ReturnType<typeof accountLedger>>): Promise<Uint8Array> {
  const { w } = await start(ctx, `Account ${l.account.number} ${l.account.name}`, `${formatDate(l.period.from)} – ${formatDate(l.period.to)}`);
  table(
    w,
    [
      { label: "Date", width: 13 },
      { label: "Ref.", width: 13 },
      { label: "Description", width: 38 },
      { label: "Contra", width: 22 },
      { label: "Debit", width: 15, align: "right" },
      { label: "Credit", width: 15, align: "right" },
      { label: "Balance", width: 16, align: "right" },
    ],
    [
      { cells: ["", "", "Opening balance", "", "", "", formatAmount(l.opening)], bold: true },
      ...l.rows.map((r) => ({
        cells: [formatDate(r.date), r.ref_nr ?? "", r.description ?? "", r.contra ?? "", r.debit ? formatAmount(r.debit) : "", r.credit ? formatAmount(r.credit) : "", formatAmount(r.balance)],
      })),
      { cells: ["", "", "Closing balance", "", formatAmount(l.totals.debit), formatAmount(l.totals.credit), formatAmount(l.closing)], bold: true, shade: true },
    ],
  );
  w.finalizeFooters("Generated by Batzio");
  return w.save();
}

export async function renderVatPdf(ctx: Ctx, v: Awaited<ReturnType<typeof vatReport>>): Promise<Uint8Array> {
  const { w, company } = await start(ctx, "VAT return (effective method)", `${formatDate(v.period.from)} – ${formatDate(v.period.to)}`);
  if (company.vat_number) {
    w.text(`VAT number: ${company.vat_number}`, w.margin.left, w.y, { size: 9 });
    w.y += 18;
  }
  const d = v.digits as Record<string, number>;
  const row = (digit: string, base: number | null, tax: number | null, bold = false) => ({
    cells: [digit, VAT_FORM_DIGITS[digit] ?? "", base === null ? "" : formatAmount(base), tax === null ? "" : formatAmount(tax)],
    bold,
    shade: bold,
  });
  table(
    w,
    [
      { label: "Digit", width: 10 },
      { label: "Description", width: 60 },
      { label: "Turnover / base", width: 20, align: "right" },
      { label: "Tax", width: 18, align: "right" },
    ],
    [
      row("200", d["200"], null),
      row("221", d["221"], null),
      row("230", d["230"], null),
      row("289", d["289"], null),
      row("299", d["299"], null, true),
      row("303", d["303"], d["303_tax"]),
      row("313", d["313"], d["313_tax"]),
      row("343", d["343"], d["343_tax"]),
      row("399", null, d["399"], true),
      row("400", null, d["400"]),
      row("405", null, d["405"]),
      row("479", null, d["479"], true),
      row("500", null, d["500"], true),
      row("510", null, d["510"], true),
    ],
  );
  w.y += 16;
  w.text("Details by VAT code", w.margin.left, w.y, { size: 11, bold: true });
  w.y += 18;
  table(
    w,
    [
      { label: "Code", width: 12 },
      { label: "Name", width: 52 },
      { label: "Base", width: 22, align: "right" },
      { label: "Tax", width: 22, align: "right" },
    ],
    v.lines.map((l) => ({ cells: [l.code, l.name, formatAmount(l.base), formatAmount(l.tax)] })),
  );
  w.finalizeFooters("Figures for the ESTV VAT return. Please verify before submission.");
  return w.save();
}

export interface PayslipPdfData {
  employee: Record<string, unknown>;
  slip: Record<string, unknown>;
}

export async function renderPayslipPdf(ctx: Ctx, { employee, slip }: PayslipPdfData): Promise<Uint8Array> {
  const period = `${String(slip.month).padStart(2, "0")}/${slip.year}`;
  const { w } = await start(ctx, `Payslip ${period}`, `${employee.firstname} ${employee.lastname}`);
  const lines: [string, string][] = [
    ["Employee", `${employee.firstname} ${employee.lastname}${employee.nr ? ` (${employee.nr})` : ""}`],
    ["AHV number", String(employee.ahv_number ?? "—")],
    ["Job title", String(employee.job_title ?? "—")],
    ["Workload", `${employee.workload_percent ?? 100}%`],
    ["Salary IBAN", String(employee.iban ?? "—")],
  ];
  for (const [k, v] of lines) {
    w.text(k, w.margin.left, w.y, { size: 9, color: COLORS.muted });
    w.text(v, w.margin.left + 40 * MM, w.y, { size: 9 });
    w.y += 13;
  }
  w.y += 10;
  const money = (key: string) => formatAmount(Number(slip[key] ?? 0));
  const neg = (key: string) => (Number(slip[key]) ? `- ${money(key)}` : "");
  table(
    w,
    [
      { label: "Item", width: 70 },
      { label: "CHF", width: 30, align: "right" },
    ],
    [
      { cells: ["Gross salary", money("gross")], bold: true },
      { cells: ["AHV/IV/EO contribution", neg("ahv")] },
      { cells: ["Unemployment insurance (ALV)", neg("alv")] },
      { cells: ["Occupational pension (BVG)", neg("bvg")] },
      { cells: ["Non-occupational accident insurance (NBU)", neg("nbu")] },
      { cells: ["Daily sickness allowance insurance (KTG)", neg("ktg")] },
      { cells: ["Withholding tax", neg("withholding_tax")] },
      { cells: ["Family allowances", Number(slip.allowances) ? `+ ${money("allowances")}` : ""] },
      { cells: ["Net salary", money("net")], bold: true, shade: true },
    ],
  );
  w.y += 10;
  w.text(`Employer cost: CHF ${money("employer_cost")}`, w.margin.left, w.y, { size: 8.5, color: COLORS.muted });
  w.finalizeFooters("Confidential");
  return w.save();
}
